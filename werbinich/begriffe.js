const ids = new Set(FRAGEN.map((f) => f.id));
const list = (s) => String(s || '').split(/\s+/).filter(Boolean);

function expand(kat, row) {
  const [id, n, e, ja, teils, nein] = row;
  const base = BASE[kat];
  const a = {};
  for (const f of FRAGEN) a[f.id] = 'nein';
  const put = (s, v) => { for (const q of list(s)) { if (!ids.has(q)) throw new Error(`Unbekannte Frage ${q} bei ${id}`); a[q] = v; } };
  put(base.j, 'ja'); put(base.t, 'teils');
  put(ja, 'ja'); put(teils, 'teils'); put(nein, 'nein');
  return { id, n, k: kat, e, a };
}

export const BEGRIFFE = Object.entries(ROWS).flatMap(([kat, rows]) => rows.map((r) => expand(kat, r)));

export const frage = (id) => FRAGEN.find((f) => f.id === id) || null;
export const begriff = (id) => BEGRIFFE.find((b) => b.id === id) || null;
// 'ja' | 'nein' | 'teils' (oder null bei unbekannter Id)
export const antwort = (b, fid) => (b && b.a && b.a[fid]) || null;
export const imKatalog = (k) => BEGRIFFE.filter((b) => b.k === k);
